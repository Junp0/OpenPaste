import AppKit
import Testing
import ClipboardCore
@testable import ClipShelf

@Suite @MainActor struct ClipboardCaptureTests {
    private func withBoard(_ operation: (NSPasteboard) throws -> Void) rethrows {
        let board = NSPasteboard(name: .init("io.clipshelf.tests.\(UUID().uuidString)"))
        defer { board.releaseGlobally() }
        try operation(board)
    }
    @Test func textAndRichFormatsSurviveCapture() throws {
        try withBoard { board in
            let item = NSPasteboardItem()
            item.setString("你好，ClipShelf", forType: .string)
            item.setString("<b>你好，ClipShelf</b>", forType: .html)
            board.writeObjects([item])
            guard case .captured(let draft) = ClipboardCapture.read(board, source: nil) else { Issue.record("文本未被捕获"); return }
            #expect(draft.kind == .text)
            #expect(draft.text == "你好，ClipShelf")
            #expect(draft.payload.items[0].count == 2)
            let databaseURL = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString).appendingPathComponent("history.sqlite")
            defer { try? FileManager.default.removeItem(at: databaseURL.deletingLastPathComponent()) }
            let database = try ClipboardDatabase(url: databaseURL)
            let id = try database.save(draft)
            let payload = try database.payload(for: id)
            board.clearContents()
            let restored = NSPasteboardItem()
            for representation in payload.items[0] { restored.setData(representation.data, forType: .init(representation.type)) }
            board.writeObjects([restored])
            #expect(board.string(forType: .string) == "你好，ClipShelf")
            #expect(board.string(forType: .html) == "<b>你好，ClipShelf</b>")
        }
    }
    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
    func sensitiveOrTemporaryContentsAreIgnored(marker: String) {
        withBoard { board in
            let item = NSPasteboardItem(); item.setString("do not save", forType: .string)
            item.setString("", forType: .init(marker)); board.writeObjects([item])
            guard case .ignored = ClipboardCapture.read(board, source: nil) else { Issue.record("带有敏感标记的内容不应被记录"); return }
        }
    }
    @Test func oversizeContentIsSkipped() {
        withBoard { board in
            board.setData(Data(repeating: 97, count: ClipboardCapture.maximumBytes + 1), forType: .string)
            guard case .tooLarge = ClipboardCapture.read(board, source: nil) else { Issue.record("超大内容不应被记录"); return }
        }
    }
    @Test func urlIsRecognizedWithoutFetchingNetworkContent() {
        withBoard { board in
            board.setString("https://example.com/docs?q=中文", forType: .string)
            guard case .captured(let draft) = ClipboardCapture.read(board, source: nil) else { Issue.record("链接未被捕获"); return }
            #expect(draft.kind == .link); #expect(draft.title == "example.com")
        }
    }
    @Test func imageHasThumbnailAndOriginalPayload() throws {
        try withBoard { board in
            let bitmap = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 32, pixelsHigh: 24, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
            let png = try #require(bitmap.representation(using: .png, properties: [:]))
            board.setData(png, forType: .png)
            guard case .captured(let draft) = ClipboardCapture.read(board, source: nil) else { Issue.record("图片未被捕获"); return }
            #expect(draft.kind == .image); #expect(draft.title == "32 × 24")
            #expect(draft.thumbnail != nil); #expect(draft.payload.items[0][0].data == png)
        }
    }
    @Test func multipleFileReferencesKeepTheirBoundaries() {
        withBoard { board in
            let items = ["file:///tmp/a.txt", "file:///tmp/b.txt"].map { url in
                let item = NSPasteboardItem(); item.setString(url, forType: .fileURL); return item
            }
            board.writeObjects(items)
            guard case .captured(let draft) = ClipboardCapture.read(board, source: nil) else { Issue.record("文件引用未被捕获"); return }
            #expect(draft.kind == .file); #expect(draft.payload.items.count == 2)
            #expect(draft.text == "/tmp/a.txt\n/tmp/b.txt")
        }
    }

    @Test func uncachedSnapshotKeepsTextFormatsAndExistingFingerprints() throws {
        try withBoard { board in
            let item = NSPasteboardItem()
            item.setString("中文与 English", forType: .string)
            item.setString("<b>中文与 English</b>", forType: .html)
            board.writeObjects([item])
            guard case .captured(let expected) = ClipboardCapture.read(board, source: nil),
                  case .captured(let snapshot) = ClipboardCapture.readUncached(board.name, source: nil) else {
                Issue.record("临时快照应捕获多格式文本"); return
            }
            #expect(snapshot.text == expected.text)
            #expect(snapshot.payload.fingerprint == expected.payload.fingerprint)
            let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
            defer { try? FileManager.default.removeItem(at: directory) }
            let database = try ClipboardDatabase(url: directory.appendingPathComponent("history.sqlite"))
            #expect(try database.save(expected) == database.save(snapshot))
        }
    }

    @Test func uncachedSnapshotPreservesImagesAndMultipleFileItems() throws {
        try withBoard { board in
            let bitmap = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 32, pixelsHigh: 24,
                bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
            memset(try #require(bitmap.bitmapData), 128, bitmap.bytesPerRow * bitmap.pixelsHigh)
            let png = try #require(bitmap.representation(using: .png, properties: [:]))
            board.setData(png, forType: .png)
            guard case .captured(let image) = ClipboardCapture.readUncached(board.name, source: nil) else {
                Issue.record("临时快照应捕获图片"); return
            }
            #expect(image.title == "32 × 24")
            #expect(image.thumbnail != nil)
            #expect(image.payload.items.first?.first?.data == png)
            board.clearContents()
            let files = ["file:///tmp/a.txt", "file:///tmp/b.txt"].map { value in
                let item = NSPasteboardItem(); item.setString(value, forType: .fileURL); return item
            }
            board.writeObjects(files)
            guard case .captured(let snapshot) = ClipboardCapture.readUncached(board.name, source: nil),
                  case .captured(let expected) = ClipboardCapture.read(board, source: nil) else {
                Issue.record("临时快照应捕获文件引用"); return
            }
            #expect(snapshot.kind == .file)
            #expect(snapshot.text == "/tmp/a.txt\n/tmp/b.txt")
            #expect(snapshot.payload.items.count == 2)
            #expect(snapshot.payload.fingerprint == expected.payload.fingerprint)
        }
    }

    @Test func uncachedSnapshotRejectsSensitiveMarkersAndOversizePayloads() {
        withBoard { board in
            let item = NSPasteboardItem()
            item.setString("secret", forType: .string)
            item.setString("", forType: .init("org.nspasteboard.ConcealedType"))
            board.writeObjects([item])
            guard case .ignored = ClipboardCapture.readUncached(board.name, source: nil) else {
                Issue.record("临时快照不应保存敏感内容"); return
            }
            board.clearContents()
            board.setData(Data(repeating: 97, count: ClipboardCapture.maximumBytes + 1), forType: .string)
            guard case .tooLarge = ClipboardCapture.readUncached(board.name, source: nil) else {
                Issue.record("临时快照不应保存超大内容"); return
            }
        }
    }
}
